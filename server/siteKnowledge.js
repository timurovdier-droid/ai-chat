/** Явно не про сайт — отвечаем шаблоном без вызова модели */
export function shouldRedirectToPhone(userText) {
  const t = userText.trim().toLowerCase();
  if (!t) return false;
  if (SITE_TOPIC_RE.test(t)) return false;
  return CLEAR_OFF_TOPIC_RE.test(t);
}

